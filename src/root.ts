import { createElement, type ComponentType, type ReactNode } from "react";
import { ConcurrentRoot } from "react-reconciler/constants.js";

import {
  createDocument,
  presentDocument,
  presentMessage,
  type TVMLDocument,
  type TVMLElement,
} from "./dom.js";
import {
  defaultRenderError,
  RenderErrorContext,
  ScreenErrorBoundary,
  type RenderError,
} from "./error-boundary.js";
import { attachEventDelegation } from "./events.js";
import { NavigationHost } from "./navigation.js";
import { reconciler } from "./reconciler.js";
import { ScreenContext, setScreenVisible, trackScreen } from "./screen.js";

type Wrapper = ComponentType<{ children?: ReactNode }>;

// [A, B] renders <A><B>{children}</B></A>.
function composeWrappers(wrapper: Wrapper | Array<Wrapper> | undefined): Wrapper | undefined {
  if (!Array.isArray(wrapper)) return wrapper;
  if (wrapper.length === 0) return undefined;
  const Composed = ({ children }: { children?: ReactNode }) =>
    wrapper.reduceRight<ReactNode>(
      (inner, Outer) => createElement(Outer, null, inner),
      children,
    );
  return Composed as Wrapper;
}

export interface RootOptions {
  /** Called for every error React reports. Defaults to `console.error`. */
  onError?: (error: unknown) => void;
  /** Errors not caught by an error boundary. Defaults to `onError`. */
  onUncaughtError?: (error: unknown) => void;
  /** Prefix for ids generated by `useId`. */
  identifierPrefix?: string;
  /**
   * Wraps the app and every screen pushed with `useNavigation()` in a single
   * tree. Put context providers here so pushed screens can see them.
   */
  wrapper?: Wrapper | Array<Wrapper>;
  /**
   * What a screen shows when it throws while rendering. Each screen (root,
   * pushed screen, modal, tab) has its own boundary. Defaults to an alert with
   * the message and a Try Again button.
   */
  renderError?: RenderError;
}

export interface TVMLRoot {
  /** The document React renders into. Present it with `presentDocument`. */
  readonly document: TVMLDocument;
  /** Render (or update) the root's content. */
  render(children: ReactNode): void;
  /** Unmount everything rendered into the root. */
  unmount(): void;
}

function defaultOnError(error: unknown): void {
  console.error("[tvml-react]", error);
}

/**
 * Create a React root that renders into a TVML document.
 *
 * Your components render the document's children: usually a single template
 * element (`<stackTemplate>`, `<divTemplate>`, ...) and optionally a `<head>`.
 * Swapping the template element re-renders the screen in place.
 */
export function createRoot(
  doc: TVMLDocument = createDocument(),
  options: RootOptions = {},
): TVMLRoot {
  const onError = options.onError ?? defaultOnError;
  const container: TVMLElement = doc.documentElement;
  const detachEvents = attachEventDelegation(doc);
  const untrack = trackScreen(doc);
  const wrapper = composeWrappers(options.wrapper);

  const fiberRoot = reconciler.createContainer(
    container,
    ConcurrentRoot,
    null,
    false,
    null,
    options.identifierPrefix ?? "",
    options.onUncaughtError ?? onError,
    onError,
    onError,
    () => {},
    null,
  );

  // Flush synchronously so the tree is complete before the document is
  // presented. TVMLKit shows an empty template as a blank screen and won't pick
  // up later mutations, while mutations to an already-presented, non-empty
  // document do show up.
  function renderSync(element: ReactNode) {
    reconciler.updateContainerSync(element, fiberRoot, null, null);
    reconciler.flushSyncWork();
  }

  return {
    document: doc,
    render(children) {
      renderSync(
        createElement(
          RenderErrorContext.Provider,
          { value: options.renderError ?? defaultRenderError },
          createElement(
            ScreenContext.Provider,
            { value: doc },
            createElement(
              NavigationHost,
              { wrapper },
              createElement(ScreenErrorBoundary, null, children),
            ),
          ),
        ),
      );
    },
    unmount() {
      renderSync(null);
      untrack();
      detachEvents();
    },
  };
}

export interface LaunchOptions extends RootOptions {
  /** Title of the default error alert. */
  errorTitle?: string;
}

/**
 * Render `children` into a fresh document and present it. If a screen throws
 * while rendering, it shows an alert with the error instead of going blank.
 */
export function launch(
  children: ReactNode,
  options: LaunchOptions = {},
): TVMLRoot | undefined {
  const { errorTitle } = options;
  const renderError: RenderError =
    options.renderError ??
    ((error, retry) => defaultRenderError(error, retry, errorTitle));

  try {
    // Render errors are caught by the root's error boundary, which shows
    // `renderError` in place of the app.
    const root = createRoot(undefined, { ...options, renderError });
    root.render(children);
    presentDocument(root.document);
    setScreenVisible(root.document, true);
    return root;
  } catch (error) {
    (options.onError ?? defaultOnError)(error);
    presentError(options, error);
    return undefined;
  }
}

function presentError(options: LaunchOptions, error: unknown): void {
  const message =
    error instanceof Error
      ? `${error.message}\n${error.stack ?? ""}`
      : String(error);
  try {
    presentMessage(options.errorTitle ?? "Something went wrong", message);
  } catch {
    // Nothing left to show it with.
  }
}
