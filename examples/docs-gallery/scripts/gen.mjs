// Lists the docs site's examples (site/src/examples/*.tsx) in
// src/examples.gen.ts, so the gallery shows exactly what the docs use.
import { readdirSync, writeFileSync } from "node:fs";

const dir = new URL("../../../site/src/examples/", import.meta.url);
const names = readdirSync(dir)
  .filter((file) => file.endsWith(".tsx"))
  .map((file) => file.slice(0, -4))
  .sort();
const id = (name) => "Example_" + name.replace(/[^a-zA-Z0-9]/g, "_");

writeFileSync(
  new URL("../src/examples.gen.ts", import.meta.url),
  `// Generated by scripts/gen.mjs from site/src/examples.\n` +
    `import type { ComponentType } from "react";\n\n` +
    names.map((name) => `import ${id(name)} from "../../../site/src/examples/${name}";`).join("\n") +
    `\n\nexport const EXAMPLES: Array<{ name: string; Component: ComponentType }> = [\n` +
    names.map((name) => `  { name: ${JSON.stringify(name)}, Component: ${id(name)} },`).join("\n") +
    `\n];\n`,
);
console.log(`${names.length} examples`);
